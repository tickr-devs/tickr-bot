"""The single recorded cause of a refused entry admission."""

from __future__ import annotations

from enum import StrEnum


class AdmissionCause(StrEnum):
    """Why an entry was refused. One value per refusal; order follows spec section 7."""

    # 1. Trading gate
    GATE_CLOSED = "GATE_CLOSED"
    # 2. Reconciliation, broker freshness, exposure, operator stop
    CLOCK_INVALID = "CLOCK_INVALID"
    RECONCILIATION_NOT_DONE = "RECONCILIATION_NOT_DONE"
    BROKER_READ_MISSING = "BROKER_READ_MISSING"
    BROKER_READ_STALE = "BROKER_READ_STALE"
    UNRESOLVED_EXPOSURE = "UNRESOLVED_EXPOSURE"
    FOREIGN_EXPOSURE = "FOREIGN_EXPOSURE"
    ENTRY_STOP_SET = "ENTRY_STOP_SET"
    # 3. Session and calendar
    CALENDAR_UNKNOWN = "CALENDAR_UNKNOWN"
    CALENDAR_DAY_MISMATCH = "CALENDAR_DAY_MISMATCH"
    HALF_DAY = "HALF_DAY"
    OUTSIDE_REGULAR_SESSION = "OUTSIDE_REGULAR_SESSION"
    BEFORE_FIRST_ENTRY = "BEFORE_FIRST_ENTRY"
    SESSION_TIMES_INVALID = "SESSION_TIMES_INVALID"
    AFTER_LAST_ENTRY = "AFTER_LAST_ENTRY"
    # 4. Own state, position limit and cooldown after a loss
    COUNT_INVALID = "COUNT_INVALID"
    OWN_POSITION_OPEN = "OWN_POSITION_OPEN"
    OWN_ORDER_WORKING = "OWN_ORDER_WORKING"
    POSITION_LIMIT_REACHED = "POSITION_LIMIT_REACHED"
    WORKING_ENTRY_LIMIT_REACHED = "WORKING_ENTRY_LIMIT_REACHED"
    SYMBOL_COOLDOWN = "SYMBOL_COOLDOWN"
    STOP_OUT_STREAK = "STOP_OUT_STREAK"
    # 5. Quote and setup
    DECISION_NOT_ENTER = "DECISION_NOT_ENTER"
    DECISION_NOT_ACTIVE = "DECISION_NOT_ACTIVE"
    STRATEGY_NOT_EXTENDED = "STRATEGY_NOT_EXTENDED"
    DECISION_INCOMPLETE = "DECISION_INCOMPLETE"
    DECISION_INVALID = "DECISION_INVALID"
    ORDER_PRICES_MISSING = "ORDER_PRICES_MISSING"
    ORDER_PRICES_INVALID = "ORDER_PRICES_INVALID"
    SETUP_INVALIDATED = "SETUP_INVALIDATED"
    QUOTE_MISSING = "QUOTE_MISSING"
    QUOTE_SYMBOL_MISMATCH = "QUOTE_SYMBOL_MISMATCH"
    QUOTE_INVALID = "QUOTE_INVALID"
    QUOTE_TIME_INVALID = "QUOTE_TIME_INVALID"
    QUOTE_STALE = "QUOTE_STALE"
    SPREAD_TOO_WIDE = "SPREAD_TOO_WIDE"
    PRICE_OUTSIDE_WINDOW = "PRICE_OUTSIDE_WINDOW"
    PRICE_COLLAR_UNKNOWN = "PRICE_COLLAR_UNKNOWN"
    PRICE_COLLAR_BREACH = "PRICE_COLLAR_BREACH"
    # 6. Size and money
    QUANTITY_BELOW_ONE = "QUANTITY_BELOW_ONE"
    QUANTITY_NOT_WHOLE = "QUANTITY_NOT_WHOLE"
    NOTIONAL_OVER_CAP = "NOTIONAL_OVER_CAP"
    PLANNED_LOSS_OVER_LIMIT = "PLANNED_LOSS_OVER_LIMIT"
    EQUITY_UNKNOWN = "EQUITY_UNKNOWN"
    DAILY_MONEY_UNKNOWN = "DAILY_MONEY_UNKNOWN"
    DAILY_MONEY_INVALID = "DAILY_MONEY_INVALID"
    DAILY_CEILING = "DAILY_CEILING"
    WEEKLY_MONEY_UNKNOWN = "WEEKLY_MONEY_UNKNOWN"
    WEEKLY_MONEY_INVALID = "WEEKLY_MONEY_INVALID"
    WEEKLY_CEILING = "WEEKLY_CEILING"
    BUYING_POWER_UNKNOWN = "BUYING_POWER_UNKNOWN"
    BUYING_POWER_SHORT = "BUYING_POWER_SHORT"
    # 7. Request budget
    ENTRY_BUDGET_UNAVAILABLE = "ENTRY_BUDGET_UNAVAILABLE"
    STOP_BUDGET_UNAVAILABLE = "STOP_BUDGET_UNAVAILABLE"
    TRADABILITY_BUDGET_UNAVAILABLE = "TRADABILITY_BUDGET_UNAVAILABLE"
    # Tradability (backlog T8; only with [risk] tradability_check_enabled), read from the
    # broker after every check above passed, before the buying power
    TRADABILITY_UNKNOWN = "TRADABILITY_UNKNOWN"
    INSTRUMENT_HALTED = "INSTRUMENT_HALTED"
    INSTRUMENT_CLOSE_ONLY = "INSTRUMENT_CLOSE_ONLY"
    INSTRUMENT_DENIED = "INSTRUMENT_DENIED"
    INSTRUMENT_NOT_TRADABLE = "INSTRUMENT_NOT_TRADABLE"


# Recorded as the cause code when admission passed but the engine refused to open the trade
# (`runtime/entries.py`); its detail is the engine's text.
ENGINE_REFUSED = "ENGINE_REFUSED"
